async def seed():
    """Заполнение БД начальными данными."""
    await init_db()

    async with async_session() as db:
        # Проверяем, есть ли уже данные
        result = await db.execute(select(Product).limit(1))
        if result.scalar_one_or_none():
            logger.info("Product seed skipped")
            return

        # Создаём теги (только категории, не алиасы)
        tag_names = set()
        for entry in SEED_PRODUCTS:
            for t in entry[6]:
                tag_names.add(t)

        tag_map: dict[str, ProductTag] = {}
        for tag_name in sorted(tag_names):
            tag = ProductTag(name=tag_name)
            db.add(tag)
            tag_map[tag_name] = tag
        await db.flush()

        # Создаём продукты
        product_map: dict[str, Product] = {}
        for entry in SEED_PRODUCTS:
            name, cal, prot, fat, carb, aliases, tags, _parent_name = entry
            product = Product(
                name=name,
                calories=cal,
                proteins=prot,
                fats=fat,
                carbs=carb,
            )
            db.add(product)
            await db.flush()
            product_map[name] = product

            # Алиасы
            for alias_name in aliases:
                alias = ProductAlias(product_id=product.id, alias=alias_name)
                db.add(alias)

            # Теги
            for tag_name in tags:
                if tag_name in tag_map:
                    member = ProductTagMember(
                        product_id=product.id,
                        tag_id=tag_map[tag_name].id,
                        weight=1.0,
                    )
                    db.add(member)

        # Устанавливаем parent_id для вариантов
        # Молоко 2.5% и 3.2% — варианты "Молоко"
        milk_parent = product_map.get("Молоко 2.5%")
        if milk_parent:
            milk_variant = product_map.get("Молоко 3.2%")
            if milk_variant:
                milk_variant.parent_id = milk_parent.id

        # Кефир 1% и 2.5%
        kefir_parent = product_map.get("Кефир 1%")
        if kefir_parent:
            kefir_variant = product_map.get("Кефир 2.5%")
            if kefir_variant:
                kefir_variant.parent_id = kefir_parent.id

        # Творог 5% и 9%
        tvorog_parent = product_map.get("Творог 5%")
        if tvorog_parent:
            tvorog_variant = product_map.get("Творог 9%")
            if tvorog_variant:
                tvorog_variant.parent_id = tvorog_parent.id

        # Сметана 15% и 20%
        smetana_parent = product_map.get("Сметана 15%")
        if smetana_parent:
            smetana_variant = product_map.get("Сметана 20%")
            if smetana_variant:
                smetana_variant.parent_id = smetana_parent.id

        await db.commit()
        logger.info("Product seed completed")


if __name__ == "__main__":
    asyncio.run(seed())
