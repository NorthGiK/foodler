def create_prompt(action, data: Any) -> str | None:
    if action not in ALL_ACTIONS:
        return None

    action_prompt = {
        "overall-analysis": GENERAL_ANALYSIS,
        "expiring-products": RUNNING_OUT,
        "recipes": SHOPPING_LIST,
        "save-money": CHEAPER,
        "healthy-food": HEALTHIER,
        "habits": GENERAL_ANALYSIS,
        "shopping-cart": SHOPPING_LIST,
        "diet": HEALTHIER,
        "ask": "Отвечай непосредственно на вопрос пользователя, опираясь только на контекст.",
        "ingredients": GENERAL_ANALYSIS,
    }.get(action, GENERAL_ANALYSIS)

    # The template contains literal JSON examples with braces.  ``str.format``
    # interprets them as replacement fields and raises ``KeyError``. Replace
    # only the two supported markers so literal braces remain in the prompt.
    return _PROMPT.replace("{INPUT_DATA}", str(data)).replace("{ACTION}", action_prompt)
