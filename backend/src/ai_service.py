"""
AI service with multi-tier routing.

Maps each action to one of three tiers:
  - Tier 1 (HYBRID): Local analytics provides verified facts to a cheap model.
  - Tier 2 (LIGHT): Cheap model (e.g. gpt-4o-mini) for simple recommendations.
  - Tier 3 (STRONG): More capable model for complex reasoning.

Usage:
    from src.ai_service import TaskRouter
    router = TaskRouter()
    sections = await router.route(action, parameters, context, db, user_id)
"""

