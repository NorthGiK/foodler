logger = logging.getLogger(__name__)


class AiServiceError(Exception):
    """Raised when the AI API returns an error or cannot be reached."""

    def __init__(self, message: str, status_code: int = 500):
        self.message = message
        self.status_code = status_code
        super().__init__(self.message)


# ---------------------------------------------------------------------------
#  Tier constants
# ---------------------------------------------------------------------------
# Actions where locally calculated facts are retained in the response and used
# as grounded context for the recommendation generated by the light model.
HYBRID_ACTIONS = frozenset(
    {
        "overall-analysis",
        "expiring-products",
        "recipes",
        "ingredients",
    }
)

# Actions best served by a cheap, fast LLM.
LIGHT_ACTIONS = frozenset(
    {
        "save-money",
        "healthy-food",
        "habits",
        "shopping-cart",
    }
)

# Actions that benefit from a more capable LLM.
STRONG_ACTIONS = frozenset(
    {
        "diet",
        "ask",
    }
)

ALL_ACTIONS = HYBRID_ACTIONS | LIGHT_ACTIONS | STRONG_ACTIONS


