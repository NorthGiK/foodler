class TaskRouter:
    """
    Routes AI requests to the appropriate tier
    based on the action type.
    """

    async def route(
        self,
        action: str,
        parameters: dict[str, Any] | None,
        context: dict[str, Any],
        db=None,
        user_id: str | None = None,
        force_light: bool = False,
    ) -> list[dict[str, Any]]:
        """
        Returns a list of AiSection-compatible dicts.

        The caller (routers/ai.py) is responsible for:
          - loading receipts and building context
          - checking credits
          - caching
        """
        if action not in ALL_ACTIONS:
            return [_section_text("Ошибка", f"Неизвестное действие: {action}")]

        values = parameters or {}
        period_from = normalize_date(values["periodFrom"]) if values.get("periodFrom") else None
        period_to = normalize_date(values["periodTo"]) if values.get("periodTo") else None

        local_facts: list[dict[str, Any]] = []
        if action in HYBRID_ACTIONS:
            if not db or not user_id:
                return [_section_text("Ошибка", "Требуется аутентификация для анализа.")]
            local_facts = await _build_local_facts(
                action, db, user_id, period_from, period_to
            )
            context = {**context, "local_facts": local_facts}

        # ---- LLM calls ----
        if force_light or action in HYBRID_ACTIONS | LIGHT_ACTIONS:
            model = AI_LIGHT_MODEL
            max_tokens = 400
            temperature = 0.2
        else:  # STRONG_ACTIONS
            model = AI_STRONG_MODEL or AI_LIGHT_MODEL
            max_tokens = 800
            temperature = 0.3

        prompt = _build_user_prompt(action, parameters, context)
        raw = await _call_llm(model, action, prompt, max_tokens=max_tokens, temperature=temperature)
        advice_sections = _coerce_sections(raw)
        return local_facts + advice_sections


# ---------------------------------------------------------------------------
#  Backward-compatible top-level function
# ---------------------------------------------------------------------------


async def generate_ai_response(
    action: str,
    parameters: dict[str, Any] | None,
    context: dict[str, Any],
    db=None,
    user_id: str | None = None,
) -> str:
    """
    Legacy entry point — maintained for tests and potential external callers.

    Returns JSON-like text for hybrid and LLM tiers.
    Prefer using TaskRouter.route() directly for new code.
    """
    router = TaskRouter()
    sections = await router.route(action, parameters, context, db=db, user_id=user_id)
    return json.dumps(sections, ensure_ascii=False)
