"""Canonical receipt-item categories and high-confidence local classification."""

from __future__ import annotations

import re

CANONICAL_CATEGORIES = frozenset(
    {
        "алкоголь",
        "бакалея",
        "бытовые товары",
        "готовая еда",
        "заморозка",
        "кондитерские",
        "колбасы",
        "молочные",
        "мясо",
        "напитки",
        "овощи",
        "прочее",
        "рыба",
        "соусы",
        "снеки",
        "фрукты",
        "хлеб",
        "яйца",
    }
)

_CATEGORY_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = tuple(
    (category, re.compile(pattern, re.IGNORECASE))
    for category, pattern in (
        (
            "бытовые товары",
            r"\b(?:салфет|бумаг[аи]?\s+туалет|порош|шампун|мыл|чистящ|моющ|"
            r"средств[оа]?\s+для|губк|пакет[ыа]?\s+для|подгуз|зубн\w*\s+паст)\w*",
        ),
        ("колбасы", r"\b(?:колбас|сервелат|сосиск|сардельк|ветчин|балык)\w*"),
        (
            "рыба",
            r"\b(?:рыб|лосос|форел|скумбр|сельд|горбуш|минтай|треск|тунц|тунец|"
            r"кревет|кальмар|мид)\w*",
        ),
        (
            "мясо",
            r"\b(?:говядин|свинин|куриц|курин|индейк|баранин|фарш|мяс|бедр|грудк)\w*",
        ),
        ("яйца", r"\b(?:яйц|яичн)\w*"),
        (
            "молочные",
            r"\b(?:молок|кефир|йогурт|творог|сыр|сметан|сливк|ряженк|простокваш|"
            r"масло\s+сливоч)\w*",
        ),
        (
            "овощи",
            r"\b(?:огур|помид|томат|картоф|морков|капуст|св[её]кл|баклаж|кабач|"
            r"перец|лук|чеснок|редис|тыкв|овощ|зелень|укроп|петруш|салат)\w*",
        ),
        (
            "фрукты",
            r"\b(?:яблок|банан|апельс|мандарин|лимон|груш|виноград|персик|абрикос|"
            r"слив[аы]?|черешн|вишн|клубник|малин|смородин|арбуз|дын|киви|манго|"
            r"фрукт|ягод)\w*",
        ),
        ("хлеб", r"\b(?:хлеб|батон|булоч|лаваш|багет|выпеч|пирож|леп[её]ш)\w*"),
        (
            "заморозка",
            r"\b(?:заморож|пельмен|вареник|морожен|наггетс|фри|овощн\w*\s+смесь)\w*",
        ),
        (
            "кондитерские",
            r"\b(?:шоколад|конфет|печень|печен|торт|вафл|мармелад|зефир|десерт|"
            r"пирожн|пряник|кекс)\w*",
        ),
        ("снеки", r"\b(?:чипс|сухарик|попкорн|крекер|снек|семечк)\w*"),
        ("соусы", r"\b(?:майонез|кетчуп|соус|горчиц|аджик)\w*"),
        ("алкоголь", r"\b(?:пив|вин[оа]?|водк|коньяк|виски|сидр|шампанск)\w*"),
        (
            "напитки",
            r"\b(?:вод[аы]?|сок|морс|нектар|чай|кофе|лимонад|газиров|напиток|"
            r"квас|компот)\w*",
        ),
        (
            "бакалея",
            r"\b(?:круп|греч|рис|макарон|паст[аы]?|мук|сахар|соль|фасол|горох|"
            r"чечевиц|нут|овсян|хлопь|специ|приправ|масло\s+(?:подсолнеч|оливков|"
            r"раститель))\w*",
        ),
        (
            "готовая еда",
            r"\b(?:салат\s+готов|сэндвич|бургер|пицц|ролл|суши|готов\w*\s+блюд|"
            r"обед\s+готов)\w*",
        ),
    )
)


def infer_category_from_name(name: str) -> str | None:
    """Return a category only for an unambiguous local name match."""
    normalized = re.sub(r"[^\w\sёЁ-]", " ", name.lower())
    normalized = re.sub(r"\s+", " ", normalized).strip()
    for category, pattern in _CATEGORY_PATTERNS:
        if pattern.search(normalized):
            return category
    return None
